// ==================== GESTION GESTUELLE TACTILE ====================

let _touchStartX = null;
let _touchStartY = null;

document.addEventListener('touchstart', e => {
  _touchStartX = e.touches[0].clientX;
  _touchStartY = e.touches[0].clientY;
}, { passive: true });

document.addEventListener('touchend', e => {
  if (_touchStartX === null || _touchStartY === null) return;
  const dx = e.changedTouches[0].clientX - _touchStartX;
  const dy = e.changedTouches[0].clientY - _touchStartY;
  _touchStartX = null;
  _touchStartY = null;

  // Filtrer pour s'assurer que c'est un balayage horizontal franc (pas un scroll)
  if (Math.abs(dx) > 75 && Math.abs(dx) > Math.abs(dy) * 1.5) {
    if (curTab === 'jour') {
      dx < 0 ? goDay(1) : goDay(-1);
    } else if (curTab === 'mois') {
      dx < 0 ? goMonth(1) : goMonth(-1);
    }
  }
}, { passive: true });

