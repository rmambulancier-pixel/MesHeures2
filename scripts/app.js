function loadArchive() {
  AD.forEach(([k, ty, deb, fin, pz, fer]) => {
    const d = { t: ty, p: [] };
    if (ty === 'T') {
      if (deb) d.deb = deb;
      if (fin) d.fin = fin;
      pz.forEach(([p1, p2, pty]) => d.p.push({ d: p1, f: p2, ty: pty }));
      if (fer || isFerie(k)) d.fer = true;
    }
    DB.days[k] = d;
  });

  AP.forEach(s => {
    if (!DB.periods.some(p => p.start === s)) DB.periods.push({ start: s, nb: 1 });
    gb(s);
  });

  DB.periods.sort((a, b) => (a.start < b.start ? -1 : 1));
  DB.s.anchor = '2025-05-19';
  DB.per = { start: '2025-05-19', nb: 1 };
  save();

  curDate = '2026-09-05';
  curMonth = '2026-09';
  renderAll();
  alert(`✅ Archive chargée : ${AD.length} journées · ${AP.length} quatorzaines.`);
}

