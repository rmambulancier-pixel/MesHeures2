function expo() {
  const now = new Date().toISOString();
  DB.exp = new Date().toLocaleDateString('fr-FR');
  save();
  const payload = { format: 'MesHeures Backup', version: MH_V, exportedAt: now, data: DB };
  const b = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(b);
  a.download = `mesheures-v15-${today()}.json`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  renderReg();
}

function impo(input) {
  const f = input.files[0];
  if (!f) return;
  const reader = new FileReader();
  reader.onload = e => {
    try {
      const raw = JSON.parse(e.target.result);
      const j = raw.data && raw.format === 'MesHeures Backup' ? raw.data : raw;
      if (!j.days) throw new Error('Structure invalide (aucun jour trouvé)');

      if (!confirm('Remplacer les données actuelles par cette sauvegarde ?\nUn point de sécurité sera créé automatiquement.')) return;

      localStorage.setItem(LS + '_preimport', JSON.stringify(DB));
      pushUndo('Import JSON V15');

      DB = {
        ...DB,
        ...j,
        s: { ...DEF, ...(j.s || {}) },
        periods: j.periods || [],
        bul: j.bul || {},
        bulletins: j.bulletins || [],
        romi: j.romi || {}
      };

      save();
      renderAll();
      alert('✅ Sauvegarde restaurée avec succès.');
    } catch (err) {
      alert('Fichier illisible : ' + err.message);
    } finally {
      input.value = '';
    }
  };
  reader.readAsText(f);
}

